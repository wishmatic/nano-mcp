func TestGenerateImageStoresAndAttachesWhatItGenerates(t *testing.T) {
	nano, submits := recordingImageNano(t, inlineResponse(testPNGBytes, testImageCost))

	store, dir := videoStore(t)

	deps := noopDeps()
	deps.NanoGPT = nanoClient(t, nano)
	deps.Files = store
	deps.Resolver = addressMap(t, "")

	result := callTool(t, connectedSession(t, deps), "generate_image", map[string]any{
		"prompt": "a lake at sunset",
		"model":  "nano-banana",
	})

	if result.IsError {
		t.Fatalf("generate_image failed: %s", errorText(result))
	}

	if len(result.Content) != 2 {
		t.Fatalf("content = %#v, want the URL and the image", result.Content)
	}

	text, ok := result.Content[0].(*mcp.TextContent)
	if !ok {
		t.Fatalf("content[0] = %T, want the URL as text", result.Content[0])
	}

	image, ok := result.Content[1].(*mcp.ImageContent)
	if !ok {
		t.Fatalf("content[1] = %T, want the image itself rather than a link", result.Content[1])
	}

	if image.MIMEType != "image/png" || !bytes.Equal(image.Data, testPNGBytes) {
		t.Errorf("image = %q of %d bytes, want the generated png", image.MIMEType, len(image.Data))
	}

	if image.Annotations == nil || !slices.Equal(image.Annotations.Audience, []mcp.Role{"user", "assistant"}) {
		t.Errorf("audience = %+v, want [user assistant], so a vision model can see it", image.Annotations)
	}

	var out struct {
		Model   string   `json:"model"`
		Count   int      `json:"count"`
		URLs    []string `json:"urls"`
		CostUSD float64  `json:"costUsd"`
	}
	structured(t, result, &out)

	if out.Model != "nano-banana" || out.Count != 1 || out.CostUSD != testImageCost {
		t.Errorf("output = %+v, want the model, one image, and the charged cost", out)
	}

	if len(out.URLs) != 1 || out.URLs[0] != text.Text {
		t.Errorf("output urls = %v, want the URL the text block carries", out.URLs)
	}

	parsed, err := url.Parse(text.Text)
	if err != nil {
		t.Fatalf("url.Parse() error: %v", err)
	}

	if parsed.Host != "nano.example.com" || !strings.HasSuffix(parsed.Path, ".png") {
		t.Errorf("url = %q, want it served as a png from the public host", text.Text)
	}

	key := filepath.FromSlash(strings.TrimPrefix(parsed.Path, "/"))

	stored, err := os.ReadFile(filepath.Join(dir, key))
	if err != nil {
		t.Fatalf("read the hosted copy: %v", err)
	}

	if !bytes.Equal(stored, testPNGBytes) {
		t.Errorf("hosted copy = %q, want the generated bytes", stored)
	}

	if body := submits.body(t); body["response_format"] != "b64_json" {
		t.Errorf("response_format = %v, want the inline form this server stores", body["response_format"])
	}
}

