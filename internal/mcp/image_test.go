// inlineResponse is the shape nano-gpt answers with when it has the bytes to hand, which is what
// asking for b64_json is for.
func inlineResponse(image []byte, cost float64) string {
	body, err := json.Marshal(map[string]any{
		"created": 1,
		"data": []map[string]string{
			{"b64_json": base64.StdEncoding.EncodeToString(image)},
		},
		"cost": cost,
	})
	if err != nil {
		panic(err)
	}

	return string(body)
}

// recordingImageNano answers one image generation, keeping the request body so a test can check
// what was sent.
func recordingImageNano(t *testing.T, response string) (string, *submitRecorder) {
	t.Helper()

	recorder := &submitRecorder{}

	nano := upstream(t, func(w http.ResponseWriter, r *http.Request) {
		if r.Method != http.MethodPost || r.URL.Path != "/api/v1/images/generations" {
			t.Errorf("upstream call = %s %s, want the images endpoint", r.Method, r.URL.Path)
		}

		var body map[string]any
		if err := json.NewDecoder(r.Body).Decode(&body); err != nil {
			t.Errorf("decode image body: %v", err)
		}

		recorder.mu.Lock()
		recorder.submit = body
		recorder.mu.Unlock()

		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write([]byte(response))
	})

	return nano, recorder
}

func upstreamJSON(t *testing.T, body string) string {
	t.Helper()

	return upstream(t, func(w http.ResponseWriter, _ *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write([]byte(body))
	})
}

func servePNG(t *testing.T) string {
	t.Helper()

	return upstream(t, func(w http.ResponseWriter, _ *http.Request) {
		w.Header().Set("Content-Type", "application/octet-stream")
		_, _ = w.Write(testPNGBytes)
	})
}
